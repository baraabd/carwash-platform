#!/usr/bin/env node
/**
 * Authors each service's initial migration from its own schema.
 *
 * `prisma migrate dev` is deliberately NOT used: it wants to create a shadow
 * database, which would force the migration role to hold CREATEDB. Keeping that
 * privilege off the migration role is part of the isolation model, so the SQL is
 * produced with `migrate diff` instead and then applied with `migrate deploy`.
 *
 * Developer utility. It writes migration SQL; it never applies anything.
 */
import { mkdir, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { ROOT, SERVICES } from '../acceptance/lib/context.mjs';
import { runOrThrow } from '../acceptance/lib/exec.mjs';

const MIGRATION = '20260920000000_sprint_02_foundation';

for (const service of SERVICES) {
  const serviceDir = path.join(ROOT, 'services', service);
  const migrationDir = path.join(serviceDir, 'prisma', 'migrations', MIGRATION);

  const existing = await readdir(path.join(serviceDir, 'prisma', 'migrations')).catch(() => []);
  if (existing.includes(MIGRATION) && !process.argv.includes('--force')) {
    console.log(`skip ${service}: migration already authored`);
    continue;
  }

  const result = await runOrThrow(
    process.execPath,
    [
      path.join(serviceDir, 'node_modules', 'prisma', 'build', 'index.js'),
      'migrate',
      'diff',
      '--from-empty',
      '--to-schema',
      path.join('prisma', 'schema.prisma'),
      '--script',
    ],
    { cwd: serviceDir, timeoutMs: 5 * 60 * 1000 },
  );

  const sql = result.stdout.trim();
  if (!sql || !/CREATE TABLE/i.test(sql)) {
    throw new Error(`EMPTY_MIGRATION for ${service}`);
  }

  await mkdir(migrationDir, { recursive: true });
  await writeFile(
    path.join(migrationDir, 'migration.sql'),
    `-- Sprint 0.2 foundation migration for the ${service} service.\n` +
      `-- Applied by the migration identity (cw_${service}_migrate) as a separate job.\n` +
      `-- Application replicas never run this file.\n\n${sql}\n`,
    'utf8',
  );
  await writeFile(
    path.join(serviceDir, 'prisma', 'migrations', 'migration_lock.toml'),
    '# Please do not edit this file manually\nprovider = "postgresql"\n',
    'utf8',
  );
  console.log(`authored services/${service}/prisma/migrations/${MIGRATION}/migration.sql`);
}
