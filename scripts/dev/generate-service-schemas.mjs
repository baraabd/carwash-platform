#!/usr/bin/env node
/**
 * Writes the service-local Prisma schemas.
 *
 * Kept as a script only so that the ten schemas cannot drift apart by hand-editing
 * their shared technical parts. It is a developer utility: it is NOT part of any
 * acceptance gate, and it never touches another service's schema file than the one
 * it is generating.
 *
 * Each service owns its own schema, its own migrations and its own generated
 * client. There is deliberately no shared business schema and no shared client.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const catalog = JSON.parse(
  await readFile(path.join(root, 'architecture/service-catalog.json'), 'utf8'),
);

const header = (service) => `// ${service} owns this schema.
//
// Generated by scripts/dev/generate-service-schemas.mjs and then committed.
// No other service may read, write or import these tables, and this file must
// never describe another service's data. There is no shared business schema.

generator client {
  provider     = "prisma-client"
  output       = "../src/generated/prisma"
  moduleFormat = "cjs"
  runtime      = "nodejs"
}

// The connection URL lives in prisma.config.ts / the environment, never here, so
// the migration identity and the runtime identity stay genuinely separate.
datasource db {
  provider = "postgresql"
}

/// Written by the migration job so a test can prove migrations really ran
/// against this database rather than assuming they did.
model ServiceMarker {
  service   String   @id
  schemaRev Int      @map("schema_rev")
  createdAt DateTime @default(now()) @map("created_at")

  @@map("service_marker")
}
`;

const outbox = `
/// Sprint 0.2 delivery slice. Disposable, non-financial, no personal data.
model FoundationProbe {
  id        String   @id @db.Uuid
  label     String   @db.VarChar(40)
  version   Int
  createdAt DateTime @default(now()) @map("created_at")

  @@map("foundation_probe")
}

/// Transactional outbox. A row here is committed in the SAME transaction as the
/// local change it describes, and is only marked published after the broker has
/// confirmed it. locked_by/locked_until implement a lease so competing relay
/// workers cannot publish or finalise the same row twice.
model OutboxMessage {
  id            String    @id @db.Uuid
  eventId       String    @unique @map("event_id") @db.Uuid
  eventType     String    @map("event_type")
  exchange      String
  routingKey    String    @map("routing_key")
  payload       String
  correlationId String    @map("correlation_id") @db.Uuid
  attempts      Int       @default(0)
  lockedBy      String?   @map("locked_by")
  lockedUntil   DateTime? @map("locked_until")
  lastError     String?   @map("last_error")
  publishedAt   DateTime? @map("published_at")
  deadAt        DateTime? @map("dead_at")
  createdAt     DateTime  @default(now()) @map("created_at")

  @@index([publishedAt, deadAt, createdAt], map: "outbox_message_pending_idx")
  @@map("outbox_message")
}
`;

const inbox = `
/// Consumer inbox. The primary key is the producer's eventId, so a redelivery
/// collides instead of producing a second local effect. payload_hash lets the
/// consumer detect the same eventId arriving with different bytes, which is an
/// integrity fault and not a retry case.
model InboxMessage {
  eventId       String   @id @map("event_id") @db.Uuid
  eventType     String   @map("event_type")
  payloadHash   String   @map("payload_hash")
  correlationId String   @map("correlation_id") @db.Uuid
  receivedAt    DateTime @default(now()) @map("received_at")

  @@map("inbox_message")
}
`;

const effects = {
  communications: `
/// Local effect of the probe slice. applyCount MUST stay at 1 for a given probe
/// no matter how often the broker redelivers the event: it is the observable
/// that makes duplicate side effects detectable instead of invisible.
model ProbeNotification {
  probeId    String   @id @map("probe_id") @db.Uuid
  label      String   @db.VarChar(40)
  applyCount Int      @default(1) @map("apply_count")
  createdAt  DateTime @default(now()) @map("created_at")

  @@map("probe_notification")
}
`,
  reporting: `
/// Read-only projection of the probe slice. applyCount MUST stay at 1 per probe;
/// a value above 1 is direct evidence of a duplicated side effect.
model ProbeProjection {
  probeId    String   @id @map("probe_id") @db.Uuid
  label      String   @db.VarChar(40)
  applyCount Int      @default(1) @map("apply_count")
  createdAt  DateTime @default(now()) @map("created_at")

  @@map("probe_projection")
}
`,
};

for (const service of catalog.services) {
  const id = service.id;
  let body = header(id);
  if (id === 'catalog') body += outbox;
  if (id === 'communications' || id === 'reporting') body += inbox + effects[id];
  const dir = path.join(root, 'services', id, 'prisma');
  await mkdir(dir, { recursive: true });
  await writeFile(path.join(dir, 'schema.prisma'), body, 'utf8');
  console.log(`wrote services/${id}/prisma/schema.prisma`);
}
